"""Sandboxed check of an AI-generated patch for the frozen VIMJ fee-balance case (V2).

Provenance of the patch under test is recorded in the evidence: it was written by Claude in the
operator's session. It is NOT blind (the model had seen the scripted fixture), it is NOT driven by
the evaluator's provider loop, and no provider, API or live call is made.

Runs through the real Bubblewrap entry point: fresh baseline (frozen test must fail with 125.00 vs
175), whole-file baseline, patch applied only to a scratch copy, frozen test after the patch, the
whole test file after the patch (no new failures), and clean-checkout integrity.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from benchmarks.real_bugs import unresolved_eval as ue
from benchmarks.real_bugs import vimj_sandbox_repair_check as sc
from mcp_server.execution_sandbox import run_untrusted_command

VERSION = ue.FREEZE_V2
UNRESOLVED = ue.ROOT / "unresolved"
PATCH_PATH = UNRESOLVED / "vimj-ai-generated-fee-balance-claude-session-v1.patch"
DIAGNOSIS_PATH = UNRESOLVED / "vimj-ai-generated-fee-balance-diagnosis-v1.md"
TEST_FILE = "tests/test_requested_changes.py"
FAILED_RE = re.compile(r"^FAILED (\S+)", re.MULTILINE)
SUMMARY_RE = re.compile(r"(\d+ (?:failed|passed|error)[^\n]*) in [\d.]+s", re.MULTILINE)


def run_pytest(directory: Path, python: Path, target: str) -> dict[str, Any]:
    outcome = sc._run(
        run_untrusted_command(
            [str(python), "-m", "pytest", "-q", target],
            cwd=directory,
            timeout=120,
            read_only_paths=[python.parents[1], Path(sys.base_prefix)],
        )
    )
    output = str(outcome.get("output", ""))
    return {
        "target": target,
        "passed": bool(outcome.get("passed")),
        "return_code": outcome.get("return_code"),
        "sandbox": outcome.get("sandbox"),
        "sandbox_unavailable": bool(outcome.get("sandbox_unavailable")),
        "failed_tests": sorted(set(FAILED_RE.findall(output))),
        "summary": (SUMMARY_RE.findall(output) or [""])[-1],
        "output_tail": sc.tail(output),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--candidate-root", type=Path, required=True)
    parser.add_argument("--evidence", type=Path, required=True)
    parser.add_argument("--patch", type=Path, default=PATCH_PATH)
    parser.add_argument("--provenance", default=None)
    parser.add_argument("--claim-level", default="ai_generated_patch_sandboxed_check")
    parser.add_argument("--generation-record", type=Path, default=None)
    parser.add_argument("--diagnosis-file", type=Path, default=None)
    parser.add_argument(
        "--recount", action="store_true", help="git apply --recount (model-written hunk counts)"
    )
    args = parser.parse_args(argv)
    patch_path = args.patch.resolve()
    apply_flags = ["--recount", "--ignore-whitespace"] if args.recount else []

    patch_text = patch_path.read_text(encoding="utf-8")
    record: dict[str, Any] = {
        "evaluation_id": VERSION.challenge_id,
        "freeze_version": VERSION.name,
        "claim_level": args.claim_level,
        "patch_provenance": args.provenance
        or (
            "AI-generated by Claude in the operator's Claude Code session; NOT blind (the model "
            "had seen the scripted fixture); NOT evaluator-driven autonomous provider run"
        ),
        "patch_path": str(patch_path),
        "patch_sha256": ue.sha256_file(patch_path),
        "patch_applied_with_flags": apply_flags,
        "diagnosis_path": str(args.diagnosis_file or DIAGNOSIS_PATH),
        "provider_calls": 0,
        "live": False,
        "started_at_utc": datetime.now(UTC).isoformat(),
        "criteria": {},
    }
    if args.generation_record is not None:
        record["generation_record"] = json.loads(args.generation_record.read_text(encoding="utf-8"))
    if args.diagnosis_file is not None:
        record["model_diagnosis"] = args.diagnosis_file.read_text(encoding="utf-8")[:4000]
    evidence_path: Path | None = None
    try:
        evidence_path = ue._ensure_private_evidence_path(args.evidence)
        ue._write_evidence(evidence_path, {**record, "status": "started"}, create=True)

        paths = ue.extract_paths(patch_text)
        record["patch_paths"] = sorted(paths)
        record["criteria"]["patch_touches_only_pinned_source"] = paths == {ue.SOURCE_PATH}

        repo = args.candidate_root.expanduser().resolve()
        backend = ue._validate_candidate(repo)
        record["clean_checkout"] = {
            "root": str(repo),
            "git_status_before": sc.git_status(repo),
            "tree_digest_before": sc.tree_digest(repo),
        }

        staged, python, baseline_output = ue._prepare_model_workspace(backend, VERSION)
        record["baseline_frozen_test"] = {"output_tail": sc.tail(baseline_output)}
        record["criteria"]["baseline_fails_for_fee_balance_assertion"] = all(
            token in baseline_output for token in sc.BASELINE_FAILURE_TOKENS
        ) and not any(marker in baseline_output for marker in sc.ENVIRONMENT_ERROR_MARKERS)
        record["baseline_whole_file"] = run_pytest(staged, python, TEST_FILE)

        ue.PREPARED_ROOT.mkdir(parents=True, exist_ok=True)
        work = Path(tempfile.mkdtemp(prefix="vimj-ai-repair-", dir=ue.PREPARED_ROOT))
        patched = work / "repo"
        shutil.copytree(staged, patched, symlinks=False)
        git = shutil.which("git")
        if git is None:
            raise ue.EvaluationSafetyError("Git executable is required")
        check = subprocess.run(  # noqa: S603 - fixed args, AI patch applied to scratch only
            [git, "apply", "--check", *apply_flags, str(patch_path)],
            cwd=patched,
            capture_output=True,
            text=True,
            timeout=60,
        )
        applied = False
        if check.returncode == 0:
            subprocess.run(  # noqa: S603 - fixed args, scratch copy only
                [git, "apply", *apply_flags, str(patch_path)], cwd=patched, check=True, timeout=60
            )
            applied = True
        fees_sha = ue.sha256_text_file(patched / ue.SOURCE_PATH)
        test_sha = ue.sha256_text_file(patched / TEST_FILE)
        record["patch"] = {
            "scratch_root": str(work),
            "git_apply_check_returncode": check.returncode,
            "git_apply_check_stderr": check.stderr[-500:],
            "applied": applied,
            "patched_fees_sha256": fees_sha,
            "differs_from_scripted_fixture_result": fees_sha != sc.POST_PATCH_FEES_SHA256,
            "patched_test_canonical_sha256": test_sha,
        }
        record["criteria"]["patch_applies_in_isolated_scratch_copy"] = applied
        record["criteria"]["frozen_test_unchanged_by_patch"] = test_sha == ue.EXPECTED_TEST_SHA256

        if applied:
            frozen = run_pytest(patched, python, ue.TEST_PATH)
            whole = run_pytest(patched, python, TEST_FILE)
            record["post_patch_frozen_test"] = frozen
            record["post_patch_whole_file"] = whole
            record["criteria"]["post_patch_frozen_test_passes_in_sandbox"] = (
                frozen["passed"] and not frozen["sandbox_unavailable"]
            )
            before = set(record["baseline_whole_file"]["failed_tests"])
            record["criteria"]["no_new_failures_in_test_file"] = (
                set(whole["failed_tests"]).issubset(before) and not whole["sandbox_unavailable"]
            )
        else:
            record["criteria"]["post_patch_frozen_test_passes_in_sandbox"] = False
            record["criteria"]["no_new_failures_in_test_file"] = False

        record["clean_checkout"]["git_status_after"] = sc.git_status(repo)
        record["clean_checkout"]["tree_digest_after"] = sc.tree_digest(repo)
        cc = record["clean_checkout"]
        record["criteria"]["clean_checkout_unchanged"] = (
            cc["git_status_before"] == cc["git_status_after"]
            and cc["tree_digest_before"] == cc["tree_digest_after"]
        )
        record["overall_pass"] = all(record["criteria"].values()) and bool(record["criteria"])
        record["status"] = "completed"
        record["completed_at_utc"] = datetime.now(UTC).isoformat()
        ue._write_evidence(evidence_path, record)
        print(
            json.dumps(
                {"overall_pass": record["overall_pass"], "criteria": record["criteria"]}, indent=2
            )
        )
        print(f"evidence: {evidence_path}")
        return 0 if record["overall_pass"] else 1
    except Exception as exc:  # fail closed, but record why
        from sentinel.scrubber import scrub_text

        record["status"] = "stopped"
        record["overall_pass"] = False
        record["stop_reason"] = scrub_text(f"{type(exc).__name__}: {exc}")
        record["stopped_at_utc"] = datetime.now(UTC).isoformat()
        if evidence_path is not None and evidence_path.exists():
            try:
                ue._write_evidence(evidence_path, record)
            except OSError:
                pass
        print(f"stopped: {record['stop_reason']}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
